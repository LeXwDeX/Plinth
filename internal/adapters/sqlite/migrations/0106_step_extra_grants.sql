-- 0106: 每个资产（一个对话会话）可以追加的 3D 步数（#330 第 5C 步），以及
-- 清单项「已在步数上限上处理过的那一轮」的记号。
--
-- 硬上限模式下，用户可以在清单抽屉或验收看板上给某一项「再给几步」。追加的
-- 步数只给这一个资产：按会话存一列，清单子会话与外部 MCP 会话共用同一条规则，
-- 判定时用「上限 + extra_steps」比较已用步数。打回重做沿用同一个子会话，所以
-- 追加的步数不会因打回清零；已用步数同样按会话计，两者生命周期一致。
--
-- asset_list_items.step_cap_turn_message_id 记录被步数上限挡住的那一轮的助手
-- 消息 ID。上限拒绝发生在该轮里，且拒绝记录会一直留在该轮；用户追加步数或调高
-- 上限后，调度器必须从新的一轮继续，而不是把同一轮再判一次（那会重新阻塞或把
-- 上限拒绝误判成失败）。空串表示没有这种情况。
--
-- 没有额外追加时默认 0、没有记号时默认空串，旧行为不变。只追加列、不回填数据；
-- 旧二进制不读这些列（查询与插入都显式列出列名），回滚到 0105 时按部署文档恢复
-- 升级前的数据库备份即可（迁移版本守卫会拒绝打开 migration 版本高于旧二进制的
-- 库），不需要手工删列。不修改 updated_at：追加步数不是会话活动，不改变会话列表
-- 的排序。
ALTER TABLE go_chat_sessions ADD COLUMN extra_steps INTEGER NOT NULL DEFAULT 0;
ALTER TABLE asset_list_items ADD COLUMN step_cap_turn_message_id TEXT NOT NULL DEFAULT '';